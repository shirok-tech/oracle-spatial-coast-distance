PROMPT === 5. Compare old and candidate distances and display bands ===
CREATE TABLE LIGHT_COAST_COMPARE AS
SELECT n.ASSET_ID,l.LOCATION_TEXT,o.NEAREST_COAST_ID AS OLD_COAST_ID,
       n.NEAREST_COAST_ID AS NEW_COAST_ID,o.COAST_DISTANCE_M AS OLD_M,
       n.COAST_DISTANCE_M AS NEW_M,
       n.COAST_DISTANCE_M-o.COAST_DISTANCE_M AS DELTA_M,
       CASE WHEN o.COAST_DISTANCE_M<100 THEN '01: 100m未満'
            WHEN o.COAST_DISTANCE_M<500 THEN '02: 100m以上500m未満'
            WHEN o.COAST_DISTANCE_M<1000 THEN '03: 500m以上1km未満'
            ELSE '04: 1km以上' END AS OLD_BAND,
       CASE WHEN n.COAST_DISTANCE_M<100 THEN '01: 100m未満'
            WHEN n.COAST_DISTANCE_M<500 THEN '02: 100m以上500m未満'
            WHEN n.COAST_DISTANCE_M<1000 THEN '03: 500m以上1km未満'
            ELSE '04: 1km以上' END AS NEW_BAND
FROM LIGHT_COAST_METRICS_CHECK n JOIN LIGHT_COAST_METRICS o ON o.ASSET_ID=n.ASSET_ID
JOIN LIGHTS l ON l.ASSET_ID=n.ASSET_ID;

SELECT COUNT(*) AS RESULT_COUNT,ROUND(MAX(ABS(DELTA_M)),6) AS MAX_ABS_DELTA_M,
       SUM(CASE WHEN ABS(DELTA_M)>0.1 THEN 1 ELSE 0 END) AS DELTA_GT_10CM,
       SUM(CASE WHEN OLD_BAND<>NEW_BAND THEN 1 ELSE 0 END) AS BAND_CHANGED,
       SUM(CASE WHEN OLD_COAST_ID<>NEW_COAST_ID THEN 1 ELSE 0 END) AS COAST_ID_CHANGED
FROM LIGHT_COAST_COMPARE;

SELECT ASSET_ID,OLD_COAST_ID,NEW_COAST_ID,ROUND(OLD_M,6) AS OLD_M,
       ROUND(NEW_M,6) AS NEW_M,ROUND(DELTA_M,6) AS DELTA_M,OLD_BAND,NEW_BAND
FROM LIGHT_COAST_COMPARE ORDER BY ABS(DELTA_M) DESC,ASSET_ID FETCH FIRST 20 ROWS ONLY;

SELECT NEW_BAND,COUNT(*) AS LIGHT_COUNT,ROUND(MIN(NEW_M),1) AS MIN_M,
       ROUND(MAX(NEW_M),1) AS MAX_M
FROM LIGHT_COAST_COMPARE GROUP BY NEW_BAND ORDER BY NEW_BAND;

PROMPT === 6. Check that omitted short lines cannot improve candidate distances ===
-- 各短線の第1頂点から設備までの距離 - PATH_BOUND_M は、その線への距離の下限。
-- 再計算距離との差を全13×271組で確認。さらに0.1mの比較余裕を設けます。
-- REF_POINTは除外影響の確認用で、海岸線レイヤーには追加しません。
CREATE TABLE COASTLINE_EXCLUSION_CHECK AS
SELECT s.COAST_ID,l.ASSET_ID,s.PATH_BOUND_M,m.COAST_DISTANCE_M AS NEW_DISTANCE_M,
       SDO_GEOM.SDO_DISTANCE(s.REF_POINT,l.GEOM,0.05,'unit=M','true')
         -s.PATH_BOUND_M-m.COAST_DISTANCE_M AS MARGIN_M
FROM COASTLINE_SHORT_CHECK s CROSS JOIN LIGHTS l
JOIN LIGHT_COAST_METRICS_CHECK m ON m.ASSET_ID=l.ASSET_ID;

SELECT COAST_ID,COUNT(*) AS LIGHT_COUNT,ROUND(MIN(MARGIN_M),6) AS MIN_MARGIN_M,
       SUM(CASE WHEN MARGIN_M<=0.1 OR MARGIN_M IS NULL THEN 1 ELSE 0 END) AS REVIEW_PAIRS
FROM COASTLINE_EXCLUSION_CHECK GROUP BY COAST_ID ORDER BY COAST_ID;

SELECT COUNT(*) AS PAIR_COUNT,ROUND(MIN(MARGIN_M),6) AS MIN_MARGIN_M,
       SUM(CASE WHEN MARGIN_M<=0.1 OR MARGIN_M IS NULL THEN 1 ELSE 0 END) AS REVIEW_PAIRS
FROM COASTLINE_EXCLUSION_CHECK;

SELECT ASSET_ID,COAST_ID,ROUND(NEW_DISTANCE_M,6) AS NEW_DISTANCE_M,
       ROUND(MARGIN_M,6) AS MARGIN_M
FROM COASTLINE_EXCLUSION_CHECK
WHERE MARGIN_M<=0.1 OR MARGIN_M IS NULL ORDER BY COAST_ID,ASSET_ID;

PROMPT === 7. Independent distance function check for selected candidate lines ===
SELECT COUNT(*) AS CHECK_COUNT,
       ROUND(MAX(ABS(m.COAST_DISTANCE_M-
         SDO_GEOM.SDO_DISTANCE(l.GEOM,c.GEOM,0.05,'unit=M','true'))),6)
         AS MAX_NN_DISTANCE_DIFF_M
FROM LIGHT_COAST_METRICS_CHECK m JOIN LIGHTS l ON l.ASSET_ID=m.ASSET_ID
JOIN COASTLINE_REPAIRED c ON c.COAST_ID=m.NEAREST_COAST_ID;

PROMPT === 8. Exhaustive minimum-distance check for five sample lights ===
-- 距離順で最小・約25/50/75パーセント・最大の5設備を選び、
-- 4978本すべてへのSDO_DISTANCEの最小値と照合します。時間がかかる場合があります。
CREATE TABLE LIGHT_COAST_FULL_SCAN_CHECK AS
WITH ranked AS (
  SELECT m.*,ROW_NUMBER() OVER(ORDER BY COAST_DISTANCE_M,ASSET_ID) AS RN,
         COUNT(*) OVER() AS TOTAL_COUNT
  FROM LIGHT_COAST_METRICS_CHECK m
)
SELECT r.ASSET_ID,r.COAST_DISTANCE_M AS NN_DISTANCE_M,
       (SELECT MIN(SDO_GEOM.SDO_DISTANCE(l.GEOM,c.GEOM,0.05,'unit=M','true'))
        FROM COASTLINE_REPAIRED c) AS FULL_SCAN_DISTANCE_M
FROM ranked r JOIN LIGHTS l ON l.ASSET_ID=r.ASSET_ID
WHERE r.RN IN (1,CEIL(r.TOTAL_COUNT*0.25),CEIL(r.TOTAL_COUNT*0.5),
              CEIL(r.TOTAL_COUNT*0.75),r.TOTAL_COUNT);

SELECT ASSET_ID,ROUND(NN_DISTANCE_M,6) AS NN_DISTANCE_M,
       ROUND(FULL_SCAN_DISTANCE_M,6) AS FULL_SCAN_DISTANCE_M,
       ROUND(ABS(NN_DISTANCE_M-FULL_SCAN_DISTANCE_M),6) AS DIFF_M
FROM LIGHT_COAST_FULL_SCAN_CHECK ORDER BY NN_DISTANCE_M,ASSET_ID;

SELECT c.COAST_TYPE,COUNT(*) AS LIGHT_COUNT
FROM LIGHT_COAST_METRICS_CHECK m JOIN COASTLINE_REPAIRED c ON c.COAST_ID=m.NEAREST_COAST_ID
GROUP BY c.COAST_TYPE ORDER BY c.COAST_TYPE;

SELECT INDEX_NAME,STATUS,DOMIDX_STATUS,DOMIDX_OPSTATUS
FROM USER_INDEXES WHERE INDEX_NAME='COASTLINE_REPAIRED_SIDX';

