BEGIN
  IF USER <> 'SPATIAL_USER' OR SYS_CONTEXT('USERENV','CURRENT_SCHEMA') <> 'SPATIAL_USER' THEN
    RAISE_APPLICATION_ERROR(-20001,'Connect as SPATIAL_USER');
  END IF;
  SELECT COUNT(*) INTO n FROM USER_OBJECTS
  WHERE OBJECT_NAME IN ('COASTLINE_PRE_FIX','LIGHT_COAST_METRICS_PRE_FIX');
  IF n <> 0 THEN RAISE_APPLICATION_ERROR(-20002,'Backup objects exist; stop and review earlier run'); END IF;
  SELECT COUNT(*) INTO n FROM LIGHT_COAST_COMPARE;
  IF n <> 271 THEN RAISE_APPLICATION_ERROR(-20003,'Expected 271 comparisons from step 05'); END IF;
  SELECT COUNT(*) INTO n FROM LIGHT_COAST_COMPARE
  WHERE DELTA_M IS NULL OR ABS(DELTA_M)>0.1 OR OLD_BAND<>NEW_BAND OR OLD_COAST_ID<>NEW_COAST_ID;
  IF n <> 0 THEN RAISE_APPLICATION_ERROR(-20004,'Unexpected step 05 comparison'); END IF;
  SELECT COUNT(*) INTO n FROM COASTLINE_EXCLUSION_CHECK;
  IF n <> 3523 THEN RAISE_APPLICATION_ERROR(-20005,'Expected 3523 exclusion checks'); END IF;
  SELECT COUNT(*) INTO n FROM COASTLINE_EXCLUSION_CHECK WHERE MARGIN_M IS NULL OR MARGIN_M<=0.1;
  IF n <> 0 THEN RAISE_APPLICATION_ERROR(-20006,'Unresolved short-line impact'); END IF;
  SELECT COUNT(*) INTO n FROM LIGHT_COAST_FULL_SCAN_CHECK;
  IF n <> 5 THEN RAISE_APPLICATION_ERROR(-20007,'Expected five full-scan checks'); END IF;
  SELECT COUNT(*) INTO n FROM LIGHT_COAST_FULL_SCAN_CHECK
  WHERE NN_DISTANCE_M IS NULL OR FULL_SCAN_DISTANCE_M IS NULL
     OR ABS(NN_DISTANCE_M-FULL_SCAN_DISTANCE_M)>0.1;
  IF n <> 0 THEN RAISE_APPLICATION_ERROR(-20008,'Full-scan check failed'); END IF;
END;
