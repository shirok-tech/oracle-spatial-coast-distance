PROMPT === 3. Back up and apply verified results in one transaction ===
DECLARE
  n NUMBER;
  PROCEDURE expect_count(actual NUMBER, expected NUMBER, message VARCHAR2) IS
  BEGIN
    IF actual <> expected THEN RAISE_APPLICATION_ERROR(-20020,message||': '||actual); END IF;
  END;
BEGIN
  LOCK TABLE COASTLINE, LIGHT_COAST_METRICS, COASTLINE_REPAIRED,
             LIGHT_COAST_METRICS_CHECK, LIGHTS IN EXCLUSIVE MODE NOWAIT;
  SELECT COUNT(*) INTO n FROM COASTLINE;
  expect_count(n,4991,'Original coastline count');
  SELECT COUNT(*) INTO n FROM COASTLINE_REPAIRED;
  expect_count(n,4978,'Repaired coastline count');
  SELECT COUNT(*) INTO n FROM LIGHTS;
  expect_count(n,271,'Light count');
  SELECT COUNT(*) INTO n FROM LIGHT_COAST_METRICS;
  expect_count(n,271,'Original distance count');
  SELECT COUNT(*) INTO n FROM LIGHT_COAST_METRICS_CHECK;
  expect_count(n,271,'Verified distance count');
  SELECT COUNT(*) INTO n FROM COASTLINE_REPAIRED c
  WHERE c.GEOM IS NULL OR NVL(c.GEOM.SDO_SRID,-1)<>4326
     OR NVL(c.GEOM.SDO_GTYPE,-1)<>2002 OR SDO_UTIL.GETNUMVERTICES(c.GEOM)<2
     OR NVL(SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT(c.GEOM,0.05),'INVALID')<>'TRUE';
  expect_count(n,0,'Invalid repaired lines');
  SELECT COUNT(*) INTO n FROM COASTLINE_REPAIRED r
  WHERE NOT EXISTS (SELECT 1 FROM COASTLINE c WHERE c.COAST_ID=r.COAST_ID);
  expect_count(n,0,'Missing original coast IDs');
  SELECT COUNT(*) INTO n FROM COASTLINE c
  WHERE NOT EXISTS (SELECT 1 FROM COASTLINE_REPAIRED r WHERE r.COAST_ID=c.COAST_ID)
    AND c.COAST_ID NOT IN (213,216,225,228,1518,1983,2176,2563,3522,3649,3708,4053,4341);
  expect_count(n,0,'Unexpected excluded coast IDs');
  SELECT COUNT(*) INTO n FROM LIGHT_COAST_METRICS m JOIN LIGHT_COAST_COMPARE q ON q.ASSET_ID=m.ASSET_ID
  JOIN LIGHT_COAST_METRICS_CHECK r ON r.ASSET_ID=m.ASSET_ID
  WHERE m.NEAREST_COAST_ID=q.OLD_COAST_ID AND m.COAST_DISTANCE_M=q.OLD_M
    AND r.NEAREST_COAST_ID=q.NEW_COAST_ID AND r.COAST_DISTANCE_M=q.NEW_M;
  expect_count(n,271,'Stored distances no longer match step 05');
  SELECT COUNT(*) INTO n FROM LIGHTS l
  JOIN LIGHT_COAST_METRICS_CHECK m ON m.ASSET_ID=l.ASSET_ID
  JOIN COASTLINE_REPAIRED c ON c.COAST_ID=m.NEAREST_COAST_ID
  WHERE l.GEOM IS NOT NULL AND l.GEOM.SDO_SRID=4326 AND l.GEOM.SDO_GTYPE=2001
    AND SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT(l.GEOM,0.05)='TRUE'
    AND m.COAST_DISTANCE_M>=0
    AND ABS(m.COAST_DISTANCE_M-SDO_GEOM.SDO_DISTANCE(l.GEOM,c.GEOM,0.05,'unit=M','true'))<=0.000001;
  expect_count(n,271,'Verified distance coverage or geometry changed');

  INSERT INTO COASTLINE_PRE_FIX SELECT * FROM COASTLINE;
  expect_count(SQL%ROWCOUNT,4991,'Coastline backup count');
  INSERT INTO LIGHT_COAST_METRICS_PRE_FIX SELECT * FROM LIGHT_COAST_METRICS;
  expect_count(SQL%ROWCOUNT,271,'Distance backup count');

  MERGE INTO COASTLINE c
  USING (SELECT COAST_ID,GEOM FROM COASTLINE_REPAIRED WHERE REPAIR_STATUS='REPAIRED_VALID') r
  ON (c.COAST_ID=r.COAST_ID)
  WHEN MATCHED THEN UPDATE SET c.GEOM=r.GEOM;
  expect_count(SQL%ROWCOUNT,458,'Repaired line update count');
  DELETE FROM COASTLINE c
  WHERE c.COAST_ID IN (213,216,225,228,1518,1983,2176,2563,3522,3649,3708,4053,4341)
    AND NOT EXISTS (SELECT 1 FROM COASTLINE_REPAIRED r WHERE r.COAST_ID=c.COAST_ID);
  expect_count(SQL%ROWCOUNT,13,'Short-line exclusion count');

  MERGE INTO LIGHT_COAST_METRICS m USING LIGHT_COAST_METRICS_CHECK r
  ON (m.ASSET_ID=r.ASSET_ID)
  WHEN MATCHED THEN UPDATE SET m.NEAREST_COAST_ID=r.NEAREST_COAST_ID,
                               m.COAST_DISTANCE_M=r.COAST_DISTANCE_M;
  expect_count(SQL%ROWCOUNT,271,'Distance update count');
  SELECT COUNT(*) INTO n FROM COASTLINE;
  expect_count(n,4978,'Adopted coastline count');
  SELECT COUNT(*) INTO n FROM COASTLINE c
  WHERE c.GEOM IS NULL OR NVL(c.GEOM.SDO_SRID,-1)<>4326 OR NVL(c.GEOM.SDO_GTYPE,-1)<>2002
     OR SDO_UTIL.GETNUMVERTICES(c.GEOM)<2
     OR NVL(SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT(c.GEOM,0.05),'INVALID')<>'TRUE';
  expect_count(n,0,'Invalid adopted coastline');
  SELECT COUNT(*) INTO n FROM LIGHT_COAST_METRICS m
  JOIN LIGHT_COAST_METRICS_CHECK r ON r.ASSET_ID=m.ASSET_ID
  WHERE m.NEAREST_COAST_ID=r.NEAREST_COAST_ID AND m.COAST_DISTANCE_M=r.COAST_DISTANCE_M;
  expect_count(n,271,'Adopted distance mismatch');
  SELECT COUNT(*) INTO n FROM V_LIGHTS_COAST;
  expect_count(n,271,'Map view row count');
  SELECT COUNT(*) INTO n FROM V_LIGHTS_COAST v JOIN LIGHT_COAST_COMPARE q ON q.ASSET_ID=v.ASSET_ID
  WHERE v.COAST_DISTANCE_M=q.NEW_M AND v.NEAREST_COAST_ID=q.NEW_COAST_ID
    AND v.COAST_DISTANCE_BAND=q.NEW_BAND
    AND v.MAP_COLOR=CASE WHEN q.NEW_M<100 THEN '#D60' WHEN q.NEW_M<500 THEN '#DA0'
                         WHEN q.NEW_M<1000 THEN '#099' ELSE '#47A' END;
  expect_count(n,271,'Map view values or color mismatch');
  SELECT COUNT(*) INTO n FROM USER_INDEXES
  WHERE INDEX_NAME='COASTLINE_SIDX' AND STATUS='VALID'
    AND DOMIDX_STATUS='VALID' AND DOMIDX_OPSTATUS='VALID';
  expect_count(n,1,'Coastline index status');
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('ADOPTION_COMMITTED: 458 lines repaired, 13 short lines excluded, 271 distances adopted.');
EXCEPTION
  WHEN OTHERS THEN
    ROLLBACK;
    DBMS_OUTPUT.PUT_LINE('ADOPTION_ROLLED_BACK. Original data retained. Do not rerun without review.');
    RAISE;
END;
