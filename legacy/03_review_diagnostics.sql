-- 1. 実行環境
SELECT USER AS LOGIN_USER,
       SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS CURRENT_SCHEMA
FROM DUAL;
SELECT BANNER_FULL FROM V$VERSION;

-- 2. 形状検証結果の全体集計。元ログは海岸線4991件中13356が471件。
WITH checks AS (
  SELECT 'COASTLINE' AS DATASET,
         NVL(SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT(c.GEOM, 0.05),
             'NULL_GEOMETRY') AS CHECK_RESULT
  FROM COASTLINE c
  UNION ALL
  SELECT 'LIGHTS',
         NVL(SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT(l.GEOM, 0.05),
             'NULL_GEOMETRY')
  FROM LIGHTS l
)
SELECT DATASET,
       CASE WHEN CHECK_RESULT = 'TRUE' THEN 'TRUE'
            ELSE REGEXP_SUBSTR(CHECK_RESULT, '^[^ ]+') END AS RESULT_CODE,
       COUNT(*) AS GEOMETRY_COUNT
FROM checks
GROUP BY DATASET,
         CASE WHEN CHECK_RESULT = 'TRUE' THEN 'TRUE'
              ELSE REGEXP_SUBSTR(CHECK_RESULT, '^[^ ]+') END
ORDER BY DATASET, RESULT_CODE;

-- 3. 不正な海岸線を頂点数で分類（正常行は省略）。
WITH checks AS (
  SELECT SDO_UTIL.GETNUMVERTICES(c.GEOM) AS VERTEX_COUNT,
         NVL(SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT(c.GEOM, 0.05),
             'NULL_GEOMETRY') AS CHECK_RESULT
  FROM COASTLINE c
)
SELECT REGEXP_SUBSTR(CHECK_RESULT, '^[^ ]+') AS RESULT_CODE,
       VERTEX_COUNT, COUNT(*) AS GEOMETRY_COUNT
FROM checks
WHERE CHECK_RESULT <> 'TRUE'
GROUP BY REGEXP_SUBSTR(CHECK_RESULT, '^[^ ]+'), VERTEX_COUNT
ORDER BY VERTEX_COUNT, RESULT_CODE;

-- 4. 頂点数の少ない不正な海岸線から30件。元ファイルを追跡する。
SELECT c.COAST_ID, c.SOURCE_FILE,
       SDO_UTIL.GETNUMVERTICES(c.GEOM) AS VERTEX_COUNT,
       SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT(c.GEOM, 0.05) AS CHECK_RESULT
FROM COASTLINE c
WHERE NVL(SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT(c.GEOM, 0.05),
          'INVALID') <> 'TRUE'
ORDER BY VERTEX_COUNT NULLS FIRST, c.COAST_ID
FETCH FIRST 30 ROWS ONLY;

-- 5. 計算用のメタデータと空間索引
SELECT TABLE_NAME, COLUMN_NAME, SRID, DIMINFO
FROM USER_SDO_GEOM_METADATA
WHERE TABLE_NAME IN ('LIGHTS', 'COASTLINE');
SELECT INDEX_NAME, TABLE_NAME, STATUS, DOMIDX_STATUS, DOMIDX_OPSTATUS
FROM USER_INDEXES
WHERE INDEX_NAME IN ('LIGHTS_SIDX', 'COASTLINE_SIDX');

-- 6. 距離値の欠損・負値と件数
SELECT COUNT(*) AS RESULT_COUNT,
       SUM(CASE WHEN COAST_DISTANCE_M IS NULL THEN 1 ELSE 0 END) AS NULL_DISTANCE_COUNT,
       SUM(CASE WHEN COAST_DISTANCE_M < 0 THEN 1 ELSE 0 END) AS NEGATIVE_DISTANCE_COUNT,
       MIN(COAST_DISTANCE_M) AS MIN_M, MAX(COAST_DISTANCE_M) AS MAX_M
FROM LIGHT_COAST_METRICS;

-- 7. 最近傍として採用された元海岸線の種別
SELECT r.COAST_TYPE, COUNT(*) AS LIGHT_COUNT
FROM LIGHT_COAST_METRICS m
LEFT JOIN COASTLINE_WGS84 r ON r.COAST_ID = m.NEAREST_COAST_ID
GROUP BY r.COAST_TYPE ORDER BY r.COAST_TYPE;
