-- SELECTのみ。初回版と06適用済み環境の両方で使用可能。

SELECT USER AS LOGIN_USER,SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AS CURRENT_SCHEMA FROM DUAL;
SELECT COUNT(*) AS TOTAL_ROWS,COUNT(DISTINCT COAST_ID) AS DISTINCT_IDS,
 SUM(CASE WHEN COAST_ID IN (213,216,225,228,1518,1983,2176,2563,3522,3649,3708,4053,4341) THEN 1 ELSE 0 END) AS EXCLUDED_IDS_REMAINING
FROM COASTLINE;
SELECT COUNT(*) AS INVALID_COUNT FROM COASTLINE c
WHERE NVL(SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT(c.GEOM,0.05),'INVALID')<>'TRUE';
SELECT COUNT(*) AS LIGHT_COUNT,COUNT(m.ASSET_ID) AS MATCHED_COUNT,
 SUM(CASE WHEN m.COAST_DISTANCE_M IS NULL OR m.COAST_DISTANCE_M<0 THEN 1 ELSE 0 END) AS BAD_DISTANCES
FROM LIGHTS l LEFT JOIN LIGHT_COAST_METRICS m ON m.ASSET_ID=l.ASSET_ID;
SELECT INDEX_NAME,STATUS,DOMIDX_STATUS,DOMIDX_OPSTATUS FROM USER_INDEXES
WHERE INDEX_NAME IN ('LIGHTS_SIDX','COASTLINE_SIDX');
-- 5. 距離区分別件数。区分は塩害・劣化の危険度を意味しない。
SELECT COAST_DISTANCE_BAND, COUNT(*) AS LIGHT_COUNT,
       ROUND(MIN(COAST_DISTANCE_M), 1) AS MIN_M,
       ROUND(MAX(COAST_DISTANCE_M), 1) AS MAX_M
FROM V_LIGHTS_COAST
GROUP BY COAST_DISTANCE_BAND ORDER BY COAST_DISTANCE_BAND;

-- 6. 海岸距離が短い順に20件表示。
SELECT ASSET_ID, MANAGEMENT_NO, LOCATION_TEXT,
       ROUND(COAST_DISTANCE_M, 1) AS COAST_DISTANCE_M,
       COAST_DISTANCE_BAND
FROM V_LIGHTS_COAST
ORDER BY COAST_DISTANCE_M NULLS LAST, ASSET_ID FETCH FIRST 20 ROWS ONLY;


SELECT ASSET_ID,COAST_DISTANCE_M,COAST_DISTANCE_BAND,MAP_COLOR FROM V_LIGHTS_COAST
WHERE ASSET_ID IN ('SZ20231004-000155','SZ20231004-000520') ORDER BY ASSET_ID;
SELECT r.COAST_TYPE,COUNT(*) AS LIGHT_COUNT
FROM LIGHT_COAST_METRICS m JOIN COASTLINE_WGS84 r ON r.COAST_ID=m.NEAREST_COAST_ID
GROUP BY r.COAST_TYPE;

