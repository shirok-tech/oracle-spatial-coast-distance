-- ADMINで実行。SPATIAL_USERをGUIで作成し、クォータを設定済みであること。
-- パスワードやウォレットをこのファイルに記載しない。
SET SERVEROUTPUT ON
SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE
 n NUMBER;
BEGIN
 IF USER<>'ADMIN' THEN RAISE_APPLICATION_ERROR(-20000,'Connect as ADMIN'); END IF;
 SELECT COUNT(*) INTO n FROM DBA_USERS WHERE USERNAME='SPATIAL_USER';
 IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Create SPATIAL_USER in Database Actions first'); END IF;
END;
/
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE,
 CREATE PROCEDURE, CREATE TYPE, CREATE SYNONYM, CREATE TRIGGER TO SPATIAL_USER;
GRANT SPATIAL_AUTHOR TO SPATIAL_USER;
ALTER USER SPATIAL_USER GRANT CONNECT THROUGH "SPATIAL$PROXY_USER";
-- 今あるデフォルトロールを残してSPATIAL_AUTHORを追加する。
DECLARE
 roles VARCHAR2(32767);
BEGIN
 SELECT LISTAGG('"'||REPLACE(GRANTED_ROLE,'"','""')||'"',', ')
        WITHIN GROUP (ORDER BY GRANTED_ROLE) INTO roles
 FROM DBA_ROLE_PRIVS
 WHERE GRANTEE='SPATIAL_USER' AND (DEFAULT_ROLE='YES' OR GRANTED_ROLE='SPATIAL_AUTHOR');
 EXECUTE IMMEDIATE 'ALTER USER SPATIAL_USER DEFAULT ROLE '||roles;
END;
/
SELECT GRANTED_ROLE,DEFAULT_ROLE FROM DBA_ROLE_PRIVS WHERE GRANTEE='SPATIAL_USER';
PROMPT Reconnect as SPATIAL_USER before continuing.
SET DEFINE ON
