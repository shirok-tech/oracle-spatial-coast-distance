-- 1. 取り込み後の列を確認。COASTLINE_WGS84の空間列がGEOM以外なら、
-- このファイルの c.GEOM を実際の空間列名へ変更する。
SELECT table_name, column_name, data_type
FROM user_tab_columns
WHERE table_name IN ('LIGHTS_SHIMODA', 'COASTLINE_WGS84')
ORDER BY table_name, column_id;

-- 2. 0件や座標・ID不備を検出。失敗したら取り込みを見直す。
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM LIGHTS_SHIMODA;
  IF n = 0 THEN RAISE_APPLICATION_ERROR(-20001, 'LIGHTS_SHIMODA is empty'); END IF;
  SELECT COUNT(*) INTO n FROM COASTLINE_WGS84;
  IF n = 0 THEN RAISE_APPLICATION_ERROR(-20002, 'COASTLINE_WGS84 is empty'); END IF;
  SELECT COUNT(*) INTO n FROM LIGHTS_SHIMODA
   WHERE ASSET_ID IS NULL OR LATITUDE IS NULL OR LONGITUDE IS NULL
      OR LATITUDE NOT BETWEEN 34 AND 36 OR LONGITUDE NOT BETWEEN 137 AND 140;
  IF n > 0 THEN RAISE_APPLICATION_ERROR(-20003, 'Invalid light ID or coordinate'); END IF;
  SELECT COUNT(*) - COUNT(DISTINCT ASSET_ID) INTO n FROM LIGHTS_SHIMODA;
  IF n > 0 THEN RAISE_APPLICATION_ERROR(-20004, 'Duplicate ASSET_ID'); END IF;
  SELECT COUNT(*) INTO n FROM COASTLINE_WGS84 c
   WHERE c.GEOM IS NULL OR c.GEOM.SDO_SRID IS NULL
      OR c.GEOM.SDO_SRID NOT IN (4326, 8307)
      OR NVL(c.GEOM.SDO_GTYPE,-1) <> 2002;
  IF n > 0 THEN RAISE_APPLICATION_ERROR(-20005, 'Coast geometry/SRID needs review'); END IF;
END;
/

-- 3. 照明灯の点を作成。CSVの座標をWGS84とみなす試行条件は本文を参照。
CREATE TABLE LIGHTS AS
SELECT r.ASSET_ID, r.SOURCE_ROW, r.OFFICE_NAME, r.ROUTE_NAME,
       r.LOCATION_TEXT, r.MANAGEMENT_NO, r.LIGHT_TYPE,
       r.LATITUDE, r.LONGITUDE,
       MDSYS.SDO_GEOMETRY(
         2001, 4326,
         MDSYS.SDO_POINT_TYPE(r.LONGITUDE, r.LATITUDE, NULL),
         NULL, NULL
       ) AS GEOM
FROM LIGHTS_SHIMODA r;

ALTER TABLE LIGHTS ADD CONSTRAINT LIGHTS_PK PRIMARY KEY (ASSET_ID);

-- 4. 変換済みGeoJSONの海岸線を共通SRIDへ統一。
CREATE TABLE COASTLINE_SOURCE AS
SELECT c.COAST_ID, c.SOURCE_FILE, c.SOURCE_FID, c.SOURCE_SRS, c.PART_NO, c.COAST_TYPE,
       CASE WHEN c.GEOM.SDO_SRID = 4326 THEN c.GEOM
            ELSE SDO_CS.TRANSFORM(c.GEOM, 4326) END AS GEOM
FROM COASTLINE_WGS84 c;

ALTER TABLE COASTLINE_SOURCE ADD CONSTRAINT COASTLINE_SOURCE_PK PRIMARY KEY (COAST_ID);


