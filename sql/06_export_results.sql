-- SQLcl専用。SELECTのみ。リポジトリ直下から実行。
-- SQL*Plus/Database Actionsでは下のSELECTを実行し、結果のCSV出力を使用。
SET ECHO OFF
SET FEEDBACK OFF
SET HEADING ON
SET PAGESIZE 0
SET SQLFORMAT csv
SET ENCODING UTF-8
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SPOOL data/generated/lights_with_coast_distance.csv
SELECT ASSET_ID,SOURCE_ROW,OFFICE_NAME,ROUTE_NAME,LOCATION_TEXT,
       MANAGEMENT_NO,LIGHT_TYPE,LATITUDE,LONGITUDE,
       NEAREST_COAST_ID,COAST_DISTANCE_M,COAST_DISTANCE_BAND,MAP_COLOR
FROM V_LIGHTS_COAST ORDER BY ASSET_ID;
SPOOL OFF
SET SQLFORMAT ansiconsole
SET FEEDBACK ON
