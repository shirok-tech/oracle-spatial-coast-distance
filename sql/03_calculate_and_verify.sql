PROMPT === 3. Bound the extent of 13 short geometries using original vertices ===
-- 原形状へ距離関数を適用せず、元の頂点を読みます。
-- 今回のWGS84・日本付近の短い直線分について、1度を120000mとして
-- 隣接頂点の経度差・緯度差の絶対値を積算し、線全体の長さの保守的上限にします。
-- 第1頂点を中心とするこの半径内に線が収まります。0.1m超や範囲外なら停止。
CREATE TABLE COASTLINE_SHORT_CHECK AS
WITH vertices AS (
  SELECT c.COAST_ID,c.SOURCE_FILE,v.ID AS VERTEX_NO,v.X AS LON,v.Y AS LAT
  FROM COASTLINE_SOURCE c JOIN COASTLINE_REPAIR_CHECK r ON r.COAST_ID=c.COAST_ID,
       TABLE(SDO_UTIL.GETVERTICES(c.GEOM)) v
  WHERE r.REPAIR_STATUS IN ('SHORT_LINE_REVIEW','CANDIDATE_REVIEW')
), steps AS (
  SELECT v.*,
         LAG(LON) OVER (PARTITION BY COAST_ID ORDER BY VERTEX_NO) AS PREV_LON,
         LAG(LAT) OVER (PARTITION BY COAST_ID ORDER BY VERTEX_NO) AS PREV_LAT
  FROM vertices v
), bounds AS (
  SELECT COAST_ID,MAX(SOURCE_FILE) AS SOURCE_FILE,COUNT(*) AS VERTEX_COUNT,
         MAX(CASE WHEN VERTEX_NO=1 THEN LON END) AS FIRST_LON,
         MAX(CASE WHEN VERTEX_NO=1 THEN LAT END) AS FIRST_LAT,
         MIN(LON) AS MIN_LON,MAX(LON) AS MAX_LON,MIN(LAT) AS MIN_LAT,MAX(LAT) AS MAX_LAT,
         SUM(CASE WHEN PREV_LON IS NULL THEN 0
                  ELSE 120000*(ABS(LON-PREV_LON)+ABS(LAT-PREV_LAT)) END) AS PATH_BOUND_M
  FROM steps GROUP BY COAST_ID
)
SELECT b.*,MDSYS.SDO_GEOMETRY(2001,4326,
       MDSYS.SDO_POINT_TYPE(FIRST_LON,FIRST_LAT,NULL),NULL,NULL) AS REF_POINT
FROM bounds b;

DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM COASTLINE_SHORT_CHECK;
  IF n <> 13 THEN RAISE_APPLICATION_ERROR(-20014,'Expected 13 short geometries'); END IF;
  SELECT COUNT(*) INTO n FROM COASTLINE_SHORT_CHECK
  WHERE VERTEX_COUNT NOT IN (2,3) OR FIRST_LON IS NULL OR FIRST_LAT IS NULL
     OR MIN_LON < 138 OR MAX_LON > 139 OR MIN_LAT < 34 OR MAX_LAT > 36
     OR PATH_BOUND_M IS NULL OR PATH_BOUND_M < 0 OR PATH_BOUND_M > 0.1;
  IF n <> 0 THEN RAISE_APPLICATION_ERROR(-20015,'Short geometry extent assumption failed'); END IF;
END;
/
SELECT COAST_ID,VERTEX_COUNT,ROUND(PATH_BOUND_M,6) AS PATH_BOUND_M,
       FIRST_LON,FIRST_LAT FROM COASTLINE_SHORT_CHECK ORDER BY COAST_ID;

