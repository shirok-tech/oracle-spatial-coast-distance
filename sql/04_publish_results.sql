CREATE TABLE COASTLINE AS SELECT * FROM COASTLINE_REPAIRED;
ALTER TABLE COASTLINE ADD CONSTRAINT COASTLINE_PK PRIMARY KEY(COAST_ID);
INSERT INTO USER_SDO_GEOM_METADATA(TABLE_NAME,COLUMN_NAME,DIMINFO,SRID)
VALUES ('COASTLINE','GEOM',MDSYS.SDO_DIM_ARRAY(
 MDSYS.SDO_DIM_ELEMENT('LONGITUDE',-180,180,0.05),
 MDSYS.SDO_DIM_ELEMENT('LATITUDE',-90,90,0.05)),4326);
COMMIT;
CREATE INDEX COASTLINE_SIDX ON COASTLINE(GEOM) INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;
CREATE TABLE LIGHT_COAST_METRICS AS SELECT * FROM LIGHT_COAST_METRICS_CHECK;
ALTER TABLE LIGHT_COAST_METRICS ADD CONSTRAINT LIGHT_COAST_METRICS_PK PRIMARY KEY(ASSET_ID);
CREATE VIEW V_LIGHTS_COAST AS
SELECT l.ASSET_ID, l.SOURCE_ROW, l.OFFICE_NAME, l.ROUTE_NAME,
       l.LOCATION_TEXT, l.MANAGEMENT_NO, l.LIGHT_TYPE,
       l.LATITUDE, l.LONGITUDE, l.GEOM,
       m.NEAREST_COAST_ID, m.COAST_DISTANCE_M,
       CASE
         WHEN m.COAST_DISTANCE_M IS NULL THEN '未計算'
         WHEN m.COAST_DISTANCE_M < 100 THEN '01: 100m未満'
         WHEN m.COAST_DISTANCE_M < 500 THEN '02: 100m以上500m未満'
         WHEN m.COAST_DISTANCE_M < 1000 THEN '03: 500m以上1km未満'
         ELSE '04: 1km以上'
       END AS COAST_DISTANCE_BAND,
       CASE
         WHEN m.COAST_DISTANCE_M IS NULL THEN '#999'
         WHEN m.COAST_DISTANCE_M < 100 THEN '#D60'
         WHEN m.COAST_DISTANCE_M < 500 THEN '#DA0'
         WHEN m.COAST_DISTANCE_M < 1000 THEN '#099'
         ELSE '#47A'
       END AS MAP_COLOR
FROM LIGHTS l LEFT JOIN LIGHT_COAST_METRICS m ON m.ASSET_ID = l.ASSET_ID;


