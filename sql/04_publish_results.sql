DECLARE
 n NUMBER;
BEGIN
 SELECT COUNT(*) INTO n FROM COASTLINE_EXCLUSION_CHECK;
 IF n<>3523 THEN RAISE_APPLICATION_ERROR(-20100,'Exclusion check incomplete'); END IF;
 SELECT COUNT(*) INTO n FROM COASTLINE_EXCLUSION_CHECK WHERE MARGIN_M IS NULL OR MARGIN_M<=0.1;
 IF n<>0 THEN RAISE_APPLICATION_ERROR(-20101,'Excluded lines may affect distances; do not publish'); END IF;
 SELECT COUNT(*) INTO n FROM LIGHT_COAST_FULL_SCAN_CHECK;
 IF n<>5 THEN RAISE_APPLICATION_ERROR(-20102,'Five sample checks required'); END IF;
 SELECT COUNT(*) INTO n FROM LIGHT_COAST_FULL_SCAN_CHECK
 WHERE NN_DISTANCE_M IS NULL OR FULL_SCAN_DISTANCE_M IS NULL
    OR ABS(NN_DISTANCE_M-FULL_SCAN_DISTANCE_M)>0.1;
 IF n<>0 THEN RAISE_APPLICATION_ERROR(-20103,'Full-scan comparison failed'); END IF;
 SELECT COUNT(*) INTO n FROM LIGHT_COAST_METRICS_CHECK m
 JOIN LIGHTS l ON l.ASSET_ID=m.ASSET_ID
 JOIN COASTLINE_REPAIRED c ON c.COAST_ID=m.NEAREST_COAST_ID
 WHERE ABS(m.COAST_DISTANCE_M-SDO_GEOM.SDO_DISTANCE(l.GEOM,c.GEOM,0.05,'unit=M','true'))<=0.000001;
 IF n<>271 THEN RAISE_APPLICATION_ERROR(-20104,'Selected-line comparison failed'); END IF;
 DBMS_OUTPUT.PUT_LINE('VERIFICATION_PASSED');
END;
