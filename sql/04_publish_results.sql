DECLARE
 n NUMBER;
BEGIN
 SELECT COUNT(*) INTO n FROM USER_OBJECTS
 WHERE OBJECT_NAME IN ('COASTLINE','LIGHT_COAST_METRICS','V_LIGHTS_COAST');
 IF n<>0 THEN RAISE_APPLICATION_ERROR(-20105,'Final tables already exist; do not overwrite'); END IF;
 SELECT COUNT(*) INTO n FROM COASTLINE_REPAIRED;
 IF n<>4978 THEN RAISE_APPLICATION_ERROR(-20106,'Expected 4978 repaired lines'); END IF;
 SELECT COUNT(*) INTO n FROM COASTLINE_REPAIRED c
 WHERE c.GEOM IS NULL OR NVL(c.GEOM.SDO_SRID,-1)<>4326 OR NVL(c.GEOM.SDO_GTYPE,-1)<>2002
 OR NVL(SDO_GEOM.VALIDATE_GEOMETRY_WITH_CONTEXT(c.GEOM,0.05),'INVALID')<>'TRUE';
 IF n<>0 THEN RAISE_APPLICATION_ERROR(-20107,'Invalid candidate geometry'); END IF;
END;
